#!/bin/bash
# ============================================================
# 每日自動執行的完整流程（由 LaunchAgent 呼叫，也可以手動跑）
# ============================================================
#   bash launch/daily_run.sh
#
# 順序很重要，而且順序本身就是一個 bug 修正：
#
#   1. 先補歷史日 K
#   2. 再產生報告與跑模擬倉
#
# 反過來的話，模擬倉會在歷史還沒到齊的時候掃描，得到一個假的
# 「今天沒有訊號」——它其實只代表沒東西可看。實際發生過：
# 2026-08-20 執行時 data/history/ 幾乎是空的，掃描池 40 檔沒幾檔
# 有 61 根 K，模擬倉照樣宣告跑完並記下 last_date，那一天就此鎖死。
#
# 現在 paperdaily 有 data_guard 會擋住那種情況（見 config/paper.yaml），
# 但「先補資料」才是真正的解法——擋住只是不讓錯誤被寫進紀錄。
# ------------------------------------------------------------
set -uo pipefail   # 刻意不用 -e：任何一步失敗都不該讓後面整串不跑

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PY="$(command -v python3 || echo /usr/bin/python3)"
cd "$ROOT"

echo "=============================================="
echo "每日執行開始 $(date '+%Y-%m-%d %H:%M:%S')"
echo "=============================================="

# --- 1. 補歷史 ---------------------------------------------
# 只補最近兩個月，已經有的月份會自動跳過，所以平常很快。
# 失敗不中斷：抓不到歷史時，持股監控報告仍然要照常產生，
# 而模擬倉那邊會被 data_guard 擋下來，不會寫出錯誤的紀錄。
echo ""
echo "[1/3] 補歷史日 K…"
if ! "$PY" src/history.py --months 2; then
  echo "⚠️  歷史回補失敗或部分失敗，繼續往下跑（模擬倉會自行判斷資料夠不夠）"
fi

# --- 2. 補中間的破洞 ---------------------------------------
# 抓到一半被中斷、或端點限流時會在已涵蓋範圍內留下缺月，
# 這不會報錯但會讓指標算錯期間。每天順手補一次，成本很低。
echo ""
echo "[2/3] 檢查並修補歷史破洞…"
if ! "$PY" src/history.py --fill-gaps; then
  echo "⚠️  破洞修補失敗，繼續往下跑"
fi

# --- 3. 報告 + 模擬倉 --------------------------------------
echo ""
echo "[3/3] 產生今日報告（模擬倉也會前進一天）…"
# --catch-up：漏掉的交易日（資料源晚更新、電腦沒開）下次執行時逐日補跑，
# 與 launch/win/daily_run.ps1 的第 3 步保持一致。
"$PY" src/main.py --quiet --catch-up
STATUS=$?

echo ""
echo "每日執行結束 $(date '+%Y-%m-%d %H:%M:%S')（main.py 結束碼 ${STATUS}）"
exit "$STATUS"
